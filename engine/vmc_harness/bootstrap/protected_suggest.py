"""보호 영역 후보 (spec 02 §보호 영역, 07 기계 사실).

코드 구조·이름·내용에서 결정적으로 찾는다(LLM 없음). 후보일 뿐 — 확정은 진단 리포트에서 사람이 [추가](명시 요청).
분류: 감사 기록 / 인증·세션·전자서명 / 시계 / 결재 상태 전이 / 생성 파일(+원본) / 운영 DB 직접 쓰기·시드 / 자격 증명 / 스키마 이력
/ 운영 접속 설정(prod_config — 이름에 운영 표시 + 접속 정보 형태. 판정은 gates.prod_config 하나를 같이 쓴다. 확정되면 읽기·그 설정으로 앱 실행도 막힌다)
"""

import ast
import json
import re
from pathlib import Path, PurePosixPath

from vmc_harness.bootstrap import util
from vmc_harness.core import config

DIR_NAME_RULES = [
    ("audit", re.compile(r"^(audit|audits)$", re.I), "감사 기록 — 남은 기록을 바꾸면 되돌릴 수 없다"),
    ("auth", re.compile(r"^(auth|authentication|reauth)$", re.I), "인증·세션"),
    ("signature", re.compile(r"^(e?signatures?|esign|signing)$", re.I), "전자서명"),
    ("clock", re.compile(r"^(clock|clocks|time[_-]?provider)$", re.I), "시계 — 바뀌면 과거 기록 시각 해석이 달라진다"),
    ("migration", re.compile(r"^(migrations?|alembic)$", re.I), "스키마 이력"),
    ("seed", re.compile(r"^(seeds?)$", re.I), "운영 데이터 시드"),
]
DIR_PATH_RULES = [
    ("auth", re.compile(r"(^|/)lib/server$"), "인증 — 서버 쪽 세션·토큰 처리"),
    ("auth", re.compile(r"(^|/)api/auth$"), "인증 API"),
]
FILE_RULES = [
    ("audit", re.compile(r"(?i)(^|/)[^/]*audit[^/]*\.sql$"), "감사 기록(테이블·SP)"),
    ("auth", re.compile(r"(^|/)(middleware\.(ts|js)|reauth\.py|auth-cookies\.(ts|js))$"), "인증·세션 진입점"),
    ("db_write", re.compile(r"(?i)(^|/)[^/]*(deploy[^/]*(database|db)|to[_-]database)[^/]*\.(py|ps1|sh|cmd|bat)$"), "운영 DB 직접 쓰기 스크립트"),
    ("credential", re.compile(r"(?i)(^|/)[^/]*(password|passwd|credential|crypto|encrypt)[^/]*\.(py|ts|tsx|js)$"), "자격 증명·암호화"),
    ("approval", re.compile(r"(?i)(^|/)[^/]*(approve|finalize|submit)[^/]*\.sql$"), "결재 상태 전이(SP)"),
]
GENERATED_NAME = re.compile(r"(?i)(\.generated\.|_pb2\.py$|\.g\.(ts|cs)$)")
GENERATED_HEAD = re.compile(r"(?i)(auto-?generated|do not edit|@generated|generated by|자동 생성된 파일|직접 수정하지 마)")
TEST_SEG = re.compile(r"(^|/)(tests?|__tests__|spec)(/|$)")
APPROVAL_FN = re.compile(r"(?i)(approve|finalize|submit)")
SAMPLE = 5  # 근거로 보여 줄 파일 예시 수(표시용)


def _approval_heavy(text):
    """결재 상태 전이 함수가 많은 파일인지(최상위·클래스 메서드 이름 기준)."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return 0
    n = 0
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and APPROVAL_FN.search(node.name):
            n += 1
    return n


def _generator_sources(root, pkg_json_rel):
    """package.json scripts가 부르는 생성 스크립트 안의 입력 파일 경로(존재하는 것만)."""
    root = Path(root)
    pkg_dir = (root / pkg_json_rel).parent
    try:
        scripts = json.loads(util.read_text(root / pkg_json_rel)).get("scripts") or {}
    except ValueError:
        return []
    out = []
    for name, cmd in scripts.items():
        if not re.search(r"(?i)(generate|template|codegen|build:)", name + " " + cmd):
            continue
        for m in re.finditer(r"node\s+([^\s&|;]+\.(?:mjs|cjs|js))", cmd):
            script = (pkg_dir / m.group(1)).resolve()
            text = util.read_text(script)
            lits = re.findall(r"['\"]([^'\"\s]+\.(?:md|json|ya?ml|csv|txt))['\"]", text)
            for args in re.findall(r"join\(([^)]*)\)", text):  # join(ROOT, "docs", "x.md")
                parts = re.findall(r"['\"]([^'\"]+)['\"]", args)
                if parts and re.search(r"\.(md|json|ya?ml|csv|txt)$", parts[-1]):
                    lits.append("/".join(parts))
            for lit in lits:
                for base in (pkg_dir, script.parent, root):
                    p = (base / lit).resolve()
                    if p.is_file():
                        out.append((util.rel(root, p), util.rel(root, script), name))
                        break
    return out


def suggest(root, source_roots=None):
    """[{glob, category, reason, evidence, command, files}]"""
    root = Path(root)
    limit = config.get("bootstrap.max_files", root)
    files, _ = util.walk_files(root, limit=limit)
    rels = [r for r in (util.rel(root, f) for f in files) if not TEST_SEG.search(r)]  # 테스트는 변조 금지 게이트 몫
    dirs = set()
    for r in rels:
        p = PurePosixPath(r).parent
        while p.as_posix() not in ("", ".") and p.parent != p:
            dirs.add(p.as_posix())
            p = p.parent
    cands = {}

    def add(glob, cat, reason, matched, command):
        c = cands.setdefault(glob, {"glob": glob, "category": cat, "reason": reason, "files": [], "command": command})
        for m in matched:
            if m not in c["files"]:
                c["files"].append(m)

    covered = []
    for d in sorted(dirs):
        name = PurePosixPath(d).name
        for cat, rx, reason in DIR_NAME_RULES:
            if rx.match(name):
                matched = [r for r in rels if r.startswith(d + "/")]
                if matched and not any(d.startswith(c + "/") for c in covered):
                    add(d + "/**", cat, reason, matched, "폴더 이름 규칙 %s" % rx.pattern)
                    covered.append(d)
        for cat, rx, reason in DIR_PATH_RULES:
            if rx.search(d):
                matched = [r for r in rels if r.startswith(d + "/")]
                if matched and not any(d.startswith(c + "/") for c in covered):
                    add(d + "/**", cat, reason, matched, "폴더 경로 규칙 %s" % rx.pattern)
                    covered.append(d)

    def under_covered(r):
        return any(r.startswith(c + "/") for c in covered)

    by_cat_dir = {}
    for r in rels:
        if under_covered(r):
            continue
        for cat, rx, reason in FILE_RULES:
            if rx.search(r):
                by_cat_dir.setdefault((cat, reason, rx.pattern, PurePosixPath(r).parent.as_posix()), []).append(r)
    for (cat, reason, pat, d), matched in sorted(by_cat_dir.items()):
        kw = {"approval": APPROVAL_FN, "audit": re.compile(r"(?i)audit")}.get(cat)
        if kw and len(matched) > 1:
            groups = {}
            for r in matched:  # 파일 이름에 실제로 쓰인 표기 그대로 glob을 만든다(대소문자)
                for w in set(kw.findall(PurePosixPath(r).name)):
                    groups.setdefault(w, []).append(r)
            for w, sub in sorted(groups.items()):
                add("%s/*%s*" % (d, w), cat, reason, sub, "파일 이름 규칙 %s" % pat)
        else:
            for r in matched:
                add(r, cat, reason, [r], "파일 이름 규칙 %s" % pat)

    # 결재 상태 전이 함수가 몰린 Python 파일
    min_fn = config.get("bootstrap.convention_min_modules", root)
    for r in rels:
        if not r.endswith(".py") or under_covered(r) or "/tests/" in "/" + r or PurePosixPath(r).name.startswith("test_"):
            continue
        n = _approval_heavy(util.read_text(root / r))
        if n >= min_fn:
            add(r, "approval", "결재 상태 전이 함수 %d개(approve·finalize·submit)" % n, [r],
                "AST: 함수 이름 /%s/ 개수" % APPROVAL_FN.pattern)

    # 생성 파일 + 원본
    for r in rels:
        if under_covered(r):
            continue
        gen = bool(GENERATED_NAME.search(r))
        if not gen and PurePosixPath(r).suffix.lower() in util.SOURCE_EXT:
            head = "\n".join(util.read_text(root / r, limit=600).splitlines()[:5])
            gen = bool(GENERATED_HEAD.search(head))
        if gen:
            add(r, "generated", "생성 파일 — 손으로 고치면 다음 생성 때 사라진다", [r], "파일 이름·머리말 규칙(generated / do not edit)")
    for r in rels:
        if PurePosixPath(r).name == "package.json":
            for src, script, sname in _generator_sources(root, r):
                add(src, "generated_source", "생성 파일의 원본(`%s` → %s) — 바꾸면 생성물·저장된 데이터 호환이 바뀐다" % (sname, script),
                    [src], "package.json scripts.%s → %s 안의 입력 경로" % (sname, script))

    # 운영 접속 설정 — 무시 폴더 밖 전부(테스트 폴더 포함 — 접속 정보는 어디 있든 같다). .env* 같은 점 파일도 본다
    from vmc_harness.gates import prod_config
    for f in files:
        if not prod_config.config_like(f.name):
            continue
        r = util.rel(root, f)
        if prod_config.classify(str(root), str(f), r) == "high" and not under_covered(r):
            add(r, "prod_config", "운영 접속 정보 — 에이전트가 읽거나 그 설정으로 앱을 띄우면 운영에 닿는다", [r],
                "파일 이름 db.prod_name_patterns + 내용 접속 정보 형태(Server=·Password=·DATABASE_URL·mssql:// 등)")

    out = []
    for c in cands.values():
        files = c.pop("files")
        c["file_count"] = len(files)
        c["examples"] = files[:SAMPLE]
        c["evidence"] = "%d개 파일 (%s)" % (len(files), ", ".join(files[:3]) + (" …" if len(files) > 3 else ""))
        out.append(c)
    order = ["audit", "approval", "auth", "signature", "clock", "credential", "prod_config", "generated", "generated_source",
             "db_write", "seed", "migration"]
    out.sort(key=lambda c: (order.index(c["category"]) if c["category"] in order else 99, c["glob"]))
    return out
